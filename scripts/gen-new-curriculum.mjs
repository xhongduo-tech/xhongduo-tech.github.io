function genIndex(tier, key, name, benchmark, chapters) {
  const meta = TIER_META[tier]
  const md = [
    '---',
    'pageClass: plain-doc',
    '---',
    '',
    `# ${name}`,
    '',
    `${benchmark}。按照「学完一个学科 = 写完该学科权威教材对应的全部博文」的标准，每写完一篇勾掉一条。`,
    '',
    '## 主题规划',
    '',
    `<ProgressGrid cat="${tier}/${key}" />`,
    '',
  ]
  chapters.forEach(([title, items], i) => {
    md.push(`### ${title}`)
    md.push('')
    items.forEach((it) => md.push(`- [ ] ${it}`))
    md.push('')
  })
  md.push('> 写作完成后：在本目录新建 `xxx.md`，然后把上面对应条目改为 `- [x] [标题](./xxx)`。')
  md.push('')
  return md.join('\n')
}

